    private void populateComboBoxes(){
        // Users
        DefaultComboBoxModel<User> userModel = new DefaultComboBoxModel<>();
        for(User u : DataStore.getInstance().getUsers()){
            userModel.addElement(u);
        }
        comboUsers.setModel(userModel);

        // Games
        DefaultComboBoxModel<Game> gameModel = new DefaultComboBoxModel<>();
        for(Game g : DataStore.getInstance().getGames()){
            gameModel.addElement(g);
        }
        comboGames.setModel(gameModel);
    }



    private void updateGameDetailsAndAvailablePlatforms(){
        Game selectedGame = (Game) comboGames.getSelectedItem();
        if(selectedGame == null)
            return;

        labelGenreValue.setText(I18n.get("rental.info.genre") + " " + selectedGame.getGenre().getDisplayName());

        int pcUnits = selectedGame.getUnits(Platform.PC);
        int ps5Units = selectedGame.getUnits(Platform.PS5);
        int switchUnits = selectedGame.getUnits(Platform.SWITCH_2);
        int xboxUnits = selectedGame.getUnits(Platform.XBOX);

        radioBtnPC.setText(formatPlatformLabel(Platform.PC, pcUnits));
        radioBtnPS5.setText(formatPlatformLabel(Platform.PS5, ps5Units));
        radioBtnSwitch2.setText(formatPlatformLabel(Platform.SWITCH_2, switchUnits));
        radioBtnXbox.setText(formatPlatformLabel(Platform.XBOX, xboxUnits));

        radioBtnPC.setEnabled(pcUnits > 0);
        radioBtnPS5.setEnabled(ps5Units > 0);
        radioBtnSwitch2.setEnabled(switchUnits > 0);
        radioBtnXbox.setEnabled(xboxUnits > 0);

        // Clear old selection and auto-select the first available platform
        buttonGroupRadBtnsSelectOne.clearSelection();
        if(pcUnits > 0) radioBtnPC.setSelected(true);
        else if (ps5Units > 0) radioBtnPS5.setSelected(true);
        else if (switchUnits > 0) radioBtnSwitch2.setSelected(true);
        else if (xboxUnits > 0) radioBtnXbox.setSelected(true);

        // Disable confirm button if no available stock on all platforms
        boolean anyAvailable = pcUnits > 0 || ps5Units > 0 || switchUnits > 0 || xboxUnits > 0;
        btnConfirm.setEnabled(anyAvailable);
    }

    private String formatPlatformLabel(Platform platform, int units){
        String key = (units == 1) ? "rental.platform.unit_single" : "rental.platform.units_plural";
        return I18n.get(key, platform.getDisplayName(), units);
    }

    private void initDatesAndRegistry(){
        DateTimeFormatter dtf = DateTimeFormatter.ofPattern("dd/MM/yyyy");
        LocalDate today = LocalDate.now();

        txtStartDate.setText(today.format(dtf));
        txtReturnDate.setText(today.plusDays(7).format(dtf));

        int nextId = DataStore.getInstance().getRentals().size() + 1;
        txtRegistryNum.setText(String.format("%02d", nextId));
    }

