    private void btnConfirmActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConfirmActionPerformed
        User user = (User) comboUsers.getSelectedItem();
        Game game = (Game) comboGames.getSelectedItem();

        Platform platform = null;
        if(radioBtnPC.isSelected()) platform = Platform.PC;
        else if(radioBtnPS5.isSelected()) platform = Platform.PS5;
        else if(radioBtnSwitch2.isSelected()) platform = Platform.SWITCH_2;
        else if(radioBtnXbox.isSelected()) platform = Platform.XBOX;

        if(platform == null){
            JOptionPane.showMessageDialog(this, I18n.get("validation.required"), "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        boolean success = DataStore.getInstance().createRental(game, user, platform);
        if(success){
            JOptionPane.showMessageDialog(this, I18n.get("msg.rental.success"), "Info", JOptionPane.INFORMATION_MESSAGE);
            dispose();
        }
    }//GEN-LAST:event_btnConfirmActionPerformed

