    private void updateRentalsTable(){
        // Localised column headers
        String[] columns = {
            I18n.get("table.col.registry_num"),
            I18n.get("table.col.game_title"),
            I18n.get("table.col.user"),
            I18n.get("table.col.platform"),
            I18n.get("table.col.start_date"),
            I18n.get("table.col.return_date"),
            I18n.get("table.col.genre")
        };
        
        DefaultTableModel model = new DefaultTableModel(columns, 0){
          @Override
          public boolean isCellEditable(int row, int col){
              return false;
          }
        };
        
        // Populate table in descending order
        List<Rental> rentals = DATA_STORE.getRentals();
        for(int i = rentals.size() - 1; i >= 0; i--){
            Rental r = rentals.get(i);
            model.addRow(new Object[]{
                String.format("%02d", r.getRegistryNumber()),
                r.getGameRented().getName(),
                r.getRenter().toString(),
                r.getGamePlatform().toString(),
                r.getStartDate().format(DATE_FORMATTER),
                r.getExpectedReturnDate().format(DATE_FORMATTER),
                r.getGameRented().getGenre().toString()
            });
        }

        tableRentals.setDefaultRenderer(Object.class, new RentalTableCellRenderer());
        tableRentals.setModel(model);
        labelTotalRentals.setText(I18n.get("app.total_rentals", rentals.size()));
    }

