    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        int choice = JOptionPane.showConfirmDialog(
                this,
                I18n.get("delete_game.confirm.message", selectedGame.toString()),
                I18n.get("delete.confirm.title"),
                JOptionPane.YES_NO_OPTION,
                JOptionPane.WARNING_MESSAGE
        );

        if(choice == JOptionPane.YES_OPTION){
            boolean deletedSuccessfully = DATA_STORE.deleteGame(selectedGame);
            if(deletedSuccessfully){
                JOptionPane.showMessageDialog(this, I18n.get("msg.game.delete_success"), "Info", JOptionPane.INFORMATION_MESSAGE);
                populateGamesTable();
                dispose();
            }
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

