    private void applyTranslations(){
        setTitle(I18n.get("delete_game.dialog.title"));
        labelGameName.setText(I18n.get("table.col.game_title"));
        labelGameGenre.setText(I18n.get("table.col.genre"));
        labelActiveRentals.setText("");
        btnDelete.setText(I18n.get("btn.delete"));
        btnClose.setText(I18n.get("btn.close"));
    }

    private void populateGamesTable(){
        String[] columns = {
                I18n.get("table.col.game_title"),
                I18n.get("table.col.genre")
        };

        DefaultTableModel tableModel = new DefaultTableModel(columns, 0){
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };

        List<Game> allGames = DATA_STORE.getGames();
        for(Game g : allGames){
            tableModel.addRow(new Object[]{
                    g.getName(),
                    g.getGenre().toString()
            });
        }

        tableGames.setModel(tableModel);
    }

    private void updateTableOnRowChange(){
        tableGames.getSelectionModel().addListSelectionListener(e -> {
            // Skip intermediate mouse events
            if(e.getValueIsAdjusting()) return;

            int selectedRowIndex = tableGames.getSelectedRow();
            if(selectedRowIndex == -1){
                selectedGame = null;
                btnDelete.setEnabled(false);
                labelGameName.setText(I18n.get("table.col.game_title"));
                labelGameGenre.setText(I18n.get("table.col.genre"));
                labelActiveRentals.setText("");
                return;
            }

            // We need an id for Game
            String selectedGameTitle = tableGames.getValueAt(selectedRowIndex, 0).toString();
            for(Game g : DATA_STORE.getGames()){
                if(g.getName().equals(selectedGameTitle)){
                    selectedGame = g;
                    break;
                }
            }

            if(selectedGame != null){
                labelGameName.setText(I18n.get("table.col.game_title") + ": " + selectedGame.getName());
                labelGameGenre.setText(I18n.get("table.col.genre") + ": " + selectedGame.getGenre().toString());

                boolean canDeleteGame = DATA_STORE.canDeleteGame(selectedGame);
                if(!canDeleteGame){
                    labelActiveRentals.setText(I18n.get("game.rentals.active"));
                    labelActiveRentals.setForeground(Color.RED);
                    btnDelete.setEnabled(false);
                } else{
                    labelActiveRentals.setText(I18n.get("game.rentals.none"));
                    labelActiveRentals.setForeground(Color.GREEN);
                    btnDelete.setEnabled(true);
                }

            }


        });
    }

