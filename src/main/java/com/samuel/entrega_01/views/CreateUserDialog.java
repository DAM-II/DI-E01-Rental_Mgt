    private void btnConfirmActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConfirmActionPerformed
        String inputName = txtName.getText().trim();
        String inputSurname1 = txtSurname1.getText().trim();
        String inputSurname2 = txtSurname2.getText().trim();
        String inputDni = txtDni.getText().trim();
        String inputPhone = txtPhone.getText().trim();

        if(inputName.isEmpty() || inputSurname1.isEmpty() || inputSurname2.isEmpty() || inputDni.isEmpty() || inputPhone.isEmpty()){
            JOptionPane.showMessageDialog(this, I18n.get("validation.required"), "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        if(!CapitalLetterValidator.isFirstLetterCapitalised(inputName) || !CapitalLetterValidator.isFirstLetterCapitalised(inputSurname1) || !CapitalLetterValidator.isFirstLetterCapitalised(inputSurname2)){
            JOptionPane.showMessageDialog(this, I18n.get("validation.name.capital"), "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        User newUser = new User(inputName, inputSurname1, inputSurname2, inputDni, inputPhone);

        boolean success = DataStore.getInstance().addUser(newUser);

        if(!success){
            JOptionPane.showMessageDialog(this, I18n.get("msg.user.already_exists"), "Error", JOptionPane.ERROR_MESSAGE);
        } else{
            JOptionPane.showMessageDialog(this, I18n.get("msg.user.create_success"), "Info", JOptionPane.INFORMATION_MESSAGE);
            dispose();
        }
    }//GEN-LAST:event_btnConfirmActionPerformed

