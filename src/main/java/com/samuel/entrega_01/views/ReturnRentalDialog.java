    private void populateActiveRentalsTable(){
        String[] columns = {
                I18n.get("table.col.registry_num"),
                I18n.get("table.col.game_title"),
                I18n.get("table.col.user"),
                I18n.get("table.col.platform"),
                I18n.get("table.col.start_date")
        };

        DefaultTableModel tableModel = new DefaultTableModel(columns, 0){
            @Override
            public boolean isCellEditable(int row, int col){
                return false;
            }
        };

        List<Rental> activeRentals = DATA_STORE.getActiveRentals();
        for(int i = activeRentals.size() - 1; i >= 0; i--){
            Rental r = activeRentals.get(i);
            tableModel.addRow(new Object[]{
                    String.format("%02d", r.getRegistryNumber()),
                    r.getGameRented().getName(),
                    r.getRenter().toString(),
                    r.getGamePlatform().toString(),
                    r.getStartDate().format(DATE_FORMATTER)
            });
        }

        tableActiveRentals.setModel(tableModel);
    }

    private void changeDataOnRowSelect(){
        tableActiveRentals.getSelectionModel().addListSelectionListener(e -> {
            // Skip intermediate mouse events
            if(e.getValueIsAdjusting()) return;

            int selectedRowIndex = tableActiveRentals.getSelectedRow();
            if(selectedRowIndex == -1){
                selectedRental = null;
                btnReturn.setEnabled(false);
                labelGameTitle.setText(I18n.get("return.field.game"));
                labelUserName.setText(I18n.get("return.field.user"));
                labelPlatform.setText(I18n.get("return.field.platform"));
                labelStartDate.setText(I18n.get("return.field.start_date"));
                labelStatus.setText(I18n.get("return.field.status"));
                return;
            }
            int registryId = Integer.parseInt(tableActiveRentals.getValueAt(selectedRowIndex, 0).toString());
            for(Rental r : DATA_STORE.getActiveRentals()){
                if(r.getRegistryNumber() == registryId){
                    selectedRental = r;
                    break;
                }
            }

            if(selectedRental != null){
                labelGameTitle.setText(I18n.get("return.field.game") + " " + selectedRental.getGameRented().getName());
                labelUserName.setText(I18n.get("return.field.user") + " " +  selectedRental.getRenter().toString());
                labelPlatform.setText(I18n.get("return.field.platform") + " " + selectedRental.getGamePlatform().toString());
                labelStartDate.setText(I18n.get("return.field.start_date") + " " + selectedRental.getStartDate().format(DATE_FORMATTER));
                labelStatus.setText(I18n.get("return.field.status") + " " + selectedRental.getStatus().name());

                btnReturn.setEnabled(true);
            }
        });
    }

