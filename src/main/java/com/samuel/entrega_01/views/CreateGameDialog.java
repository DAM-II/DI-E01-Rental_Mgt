    private void btnConfirmActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConfirmActionPerformed
        String inputName = txtName.getText().trim();
        GameGenre genre = (GameGenre) comboGenre.getSelectedItem();

        if(inputName.isEmpty()){
            JOptionPane.showMessageDialog(this, I18n.get("validation.required"), "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        if(!CapitalLetterValidator.isFirstLetterCapitalised(inputName)){
            JOptionPane.showMessageDialog(this, I18n.get("validation.name.capital"), "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        Map<Platform, Integer> stock = new HashMap<>();
        for(Platform platform : Platform.values()){
            JCheckBox chkBx = platformCheckboxes.get(platform);
            if(chkBx != null && chkBx.isSelected()){
                int units = (Integer) platformSpinners.get(platform).getValue();
                if(units > 0){
                    stock.put(platform, units);
                }
            }
        }

        if(stock.isEmpty()){
            JOptionPane.showMessageDialog(this, I18n.get("validation.game.no_platform"), "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        Game newGame = new Game(inputName, genre, stock);
        boolean success = DataStore.getInstance().addGame(newGame);
        if(!success){
            JOptionPane.showMessageDialog(this, I18n.get("msg.game.already_exists"), "Error", JOptionPane.ERROR_MESSAGE);
        } else{
            JOptionPane.showMessageDialog(this, I18n.get("msg.game.create_success"), "Info", JOptionPane.INFORMATION_MESSAGE);
            dispose();
        }
    }//GEN-LAST:event_btnConfirmActionPerformed

    private final Map<Platform, JCheckBox> platformCheckboxes = new EnumMap<>(Platform.class);
    private final Map<Platform, JSpinner> platformSpinners = new EnumMap<>(Platform.class);

    private void applyTranslations(){
        setTitle(I18n.get("game.dialog.title"));
        labelName.setText(I18n.get("game.field.name"));
        labelGenre.setText(I18n.get("game.field.genre"));
        btnConfirm.setText(I18n.get("btn.confirm"));
        btnCancel.setText(I18n.get("btn.cancel"));
        
        panelPlatforms.setBorder(
                javax.swing.BorderFactory.createTitledBorder(I18n.get("game.panel.platforms"))
        );
    }

    private void initPlatformControls(){
        panelPlatforms.setLayout(new GridLayout(0, 3, 10, 10)); // 3 cols: Checkbox, "units" and spinner

        for(Platform platform : Platform.values()){
            JCheckBox chkbx = new JCheckBox(platform.getDisplayName());
            JLabel labelUnits = new JLabel(I18n.get("game.field.units"));
            JSpinner spinner = new JSpinner(new SpinnerNumberModel(0, 0, 99, 1));
            spinner.setEnabled(false); // Disabled by default until checked

            // When checkbox is checked/unchecked, toggle the spinner
            chkbx.addActionListener(e -> {
                spinner.setEnabled(chkbx.isSelected());
                if(!chkbx.isSelected()){
                    spinner.setValue(0);
                }
            });

            platformCheckboxes.put(platform, chkbx);
            platformSpinners.put(platform, spinner);

            panelPlatforms.add(chkbx);
            panelPlatforms.add(labelUnits);
            panelPlatforms.add(spinner);
        }
    }

